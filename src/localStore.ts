/**
 * File-backed store used in local mode. Shared by every VS Code and Cursor
 * window on the machine:
 *
 *   ~/.anamnesis/local/
 *     graphs/<project>.json     { projectName, builtAt, graph }
 *     prompts/<project>.json    { projectName, rows: LocalPromptRow[] }
 *     ai-context.json           { rows: AiContextRow[] }
 *     credentials.json          { rows: CredentialSetDetail[] }  (cipher encrypted with the local key)
 *
 * Directories are 0700 and files 0600. Writes are atomic (temp + rename) and
 * read-modify-write cycles hold a short cross-process lock.
 */

export const LOCAL_ID_PREFIX = "local-";

export function isLocalId(id: string | undefined): boolean {
  return typeof id === "string" && id.startsWith(LOCAL_ID_PREFIX);
}

export interface LocalPromptRow extends PromptRow {
  /** User wanted the AI-improved prompt; generated by the cloud after sync. */
  wantAi: boolean;
}

interface StoredGraph {
  projectName: string;
  builtAt: string;
  graph: SerializedGraphPayload;
}

export function localRoot(): string {
  return path.join(os.homedir(), ".anamnesis", "local");
}

const graphsDir = () => path.join(localRoot(), "graphs");
const promptsDir = () => path.join(localRoot(), "prompts");
const aiContextFile = () => path.join(localRoot(), "ai-context.json");
const credentialsFile = () => path.join(localRoot(), "credentials.json");

const fileFor = (dir: string, name: string) => path.join(dir, `${encodeURIComponent(name)}.json`);
const nameFromFile = (file: string) => decodeURIComponent(path.basename(file, ".json"));

function ensureDir(dir: string): void {
  fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
}

function readJson<T>(file: string, fallback: T): T {
  try {
    return JSON.parse(fs.readFileSync(file, "utf-8")) as T;
  } catch {
    return fallback;
  }
}

function writeJsonAtomic(file: string, value: unknown): void {
  ensureDir(path.dirname(file));
  const tmp = `${file}.${process.pid}.${Date.now()}.tmp`;
  fs.writeFileSync(tmp, JSON.stringify(value), { encoding: "utf-8", mode: 0o600 });
  fs.renameSync(tmp, file);
}

function removeFile(file: string): boolean {
  try {
    fs.unlinkSync(file);
    return true;
  } catch {
    return false;
  }
}

function listJson(dir: string): string[] {
  try {
    return fs.readdirSync(dir).filter((f) => f.endsWith(".json")).map((f) => path.join(dir, f));
  } catch {
    return [];
  }
}

const LOCK_STALE_MS = 10_000;
const LOCK_WAIT_MS = 5_000;

function sleepSync(ms: number): void {
  Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);
}

/** Cross-process mutex (mkdir is atomic) around a read-modify-write. */
function withLock<T>(fn: () => T): T {
  ensureDir(localRoot());
  const lock = path.join(localRoot(), ".lock");
  const deadline = Date.now() + LOCK_WAIT_MS;
  for (;;) {
    try {
      fs.mkdirSync(lock);
      break;
    } catch {
      try {
        if (Date.now() - fs.statSync(lock).mtimeMs > LOCK_STALE_MS) {
          fs.rmSync(lock, { recursive: true, force: true });
          continue;
        }
      } catch {
        continue;
      }
      if (Date.now() > deadline) {
        throw new Error("Anamnesis local store is busy (another window is writing). Try again.");
      }
      sleepSync(25);
    }
  }
  try {
    return fn();
  } finally {
    fs.rmSync(lock, { recursive: true, force: true });
  }
}

const now = () => new Date().toISOString();
const newId = () => `${LOCAL_ID_PREFIX}${randomUUID()}`;

// ---------------------------------------------------------------- graphs

export function saveGraph(projectName: string, graph: SerializedGraphPayload): void {
  const stored: StoredGraph = { projectName, builtAt: now(), graph };
  writeJsonAtomic(fileFor(graphsDir(), projectName), stored);
}

export function hasGraph(projectName: string): boolean {
  return fs.existsSync(fileFor(graphsDir(), projectName));
}

export function readSerializedGraph(projectName: string): SerializedGraphPayload | undefined {
  const stored = readJson<StoredGraph | undefined>(fileFor(graphsDir(), projectName), undefined);
  return stored?.graph;
}

export function graphFileMtime(projectName: string): number {
  try {
    return fs.statSync(fileFor(graphsDir(), projectName)).mtimeMs;
  } catch {
    return 0;
  }
}

export function listGraphNames(): string[] {
  return listJson(graphsDir()).map(nameFromFile).sort((a, b) => a.localeCompare(b));
}

function countCommunities(nodes: unknown[]): number {
  const set = new Set<unknown>();
  for (const n of nodes as Array<{ community?: unknown }>) {
    if (n && n.community !== undefined && n.community !== null) set.add(n.community);
  }
  return set.size;
}

export function listProjects(): ProjectMeta[] {
  const out: ProjectMeta[] = [];
  for (const file of listJson(graphsDir())) {
    const stored = readJson<StoredGraph | undefined>(file, undefined);
    if (!stored?.graph) continue;
    const name = stored.projectName || nameFromFile(file);
    out.push({
      project_name: name,
      graph_tag: name,
      nodes: stored.graph.nodes.length,
      edges: stored.graph.edges.length,
      communities: countCommunities(stored.graph.nodes),
      built_at_commit: null,
      local: true,
    });
  }
  // Projects that only have prompts still appear (prompts tree lists projects).
  const names = new Set(out.map((p) => p.project_name));
  for (const file of listJson(promptsDir())) {
    const name = nameFromFile(file);
    if (!names.has(name)) {
      out.push({ project_name: name, graph_tag: name, built_at_commit: null, local: true });
    }
  }
  return out.sort((a, b) => a.project_name.localeCompare(b.project_name));
}

/**
 * Map the upload shape (camelCase `sourceFile`, `sourceLocation`) to the
 * download shape the graph webview reads (`source_file`, `loc`).
 */
export function toGraphData(tag: string, graph: SerializedGraphPayload): GraphData {
  const nodes = (graph.nodes as Array<Record<string, unknown>>).map((n) => {
    const loc = n.sourceLocation as { line?: number } | undefined;
    return {
      ...n,
      id: String(n.id),
      source_file: (n.source_file as string) ?? (n.sourceFile as string),
      loc: (n.loc as string) ?? (loc?.line !== undefined ? `L${loc.line}` : undefined),
    };
  });
  const edges = (graph.edges as Array<Record<string, unknown>>).map((e) => ({
    ...e,
    source: String(e.source),
    target: String(e.target),
  }));
  return { tag, nodes, edges };
}

export function getGraph(tag: string): GraphData {
  const graph = readSerializedGraph(tag);
  if (!graph) {
    throw new Error(`No local knowledge graph named "${tag}".`);
  }
  return toGraphData(tag, graph);
}

export function getStats(tag: string): GraphStats {
  const graph = readSerializedGraph(tag);
  if (!graph) {
    throw new Error(`No local knowledge graph named "${tag}".`);
  }
  return {
    tag,
    nodes: graph.nodes.length,
    edges: graph.edges.length,
    communities: countCommunities(graph.nodes),
    built_at_commit: null,
  };
}

export function deleteGraph(tag: string): string[] {
  return removeFile(fileFor(graphsDir(), tag)) ? [`local graph ${tag}`] : [];
}

// ---------------------------------------------------------------- prompts

interface PromptFile {
  projectName: string;
  rows: LocalPromptRow[];
}

const readPromptFile = (projectName: string): PromptFile =>
  readJson<PromptFile>(fileFor(promptsDir(), projectName), { projectName, rows: [] });

function writePromptFile(file: PromptFile): void {
  const target = fileFor(promptsDir(), file.projectName);
  if (file.rows.length === 0) {
    removeFile(target);
  } else {
    writeJsonAtomic(target, file);
  }
}

export function listPromptProjects(): string[] {
  return listJson(promptsDir()).map(nameFromFile);
}

export function listPrompts(projectName: string): LocalPromptRow[] {
  return readPromptFile(projectName).rows;
}

export function createPrompt(
  projectName: string,
  body: { title: string; prompt: string; promptParameters?: string; skipAiGeneration?: boolean }
): LocalPromptRow {
  return withLock(() => {
    const file = readPromptFile(projectName);
    const ts = now();
    const row: LocalPromptRow = {
      _id: newId(),
      title: body.title,
      prompt: body.prompt,
      promptParameters: body.promptParameters || "",
      aiCreatedPrompt: "",
      precision: 0,
      status: "ready",
      wantAi: body.skipAiGeneration !== true,
      createdAt: ts,
      updatedAt: ts,
    };
    file.rows.push(row);
    writePromptFile(file);
    return row;
  });
}

export function updatePrompt(
  projectName: string,
  promptId: string,
  body: { title: string; prompt: string; promptParameters?: string; skipAiGeneration?: boolean }
): LocalPromptRow {
  return withLock(() => {
    const file = readPromptFile(projectName);
    const row = file.rows.find((r) => r._id === promptId);
    if (!row) {
      throw new Error("Local prompt not found.");
    }
    row.title = body.title;
    row.prompt = body.prompt;
    row.promptParameters = body.promptParameters || "";
    row.wantAi = body.skipAiGeneration !== true;
    row.updatedAt = now();
    writePromptFile(file);
    return row;
  });
}

export function deletePrompt(projectName: string, promptId: string): boolean {
  return withLock(() => {
    const file = readPromptFile(projectName);
    const before = file.rows.length;
    file.rows = file.rows.filter((r) => r._id !== promptId);
    writePromptFile(file);
    return file.rows.length !== before;
  });
}

// ---------------------------------------------------------------- AI Context

interface RowsFile<T> {
  rows: T[];
}

const readAiContexts = () => readJson<RowsFile<AiContextRow>>(aiContextFile(), { rows: [] });

function writeRows<T>(file: string, rows: T[]): void {
  if (rows.length === 0) {
    removeFile(file);
  } else {
    writeJsonAtomic(file, { rows });
  }
}

export function listAiContexts(): AiContextRow[] {
  return readAiContexts().rows;
}

export function getAiContext(id: string): AiContextRow {
  const row = readAiContexts().rows.find((r) => r._id === id);
  if (!row) {
    throw new Error("Local AI Context not found.");
  }
  return row;
}

export function findAiContextByProject(projectName: string): AiContextRow | undefined {
  const wanted = projectName.trim().toLowerCase();
  return readAiContexts().rows.find((r) => r.projectName.trim().toLowerCase() === wanted);
}

/** Create, or replace the record with the same project name (matches the cloud). */
export function saveAiContext(body: { projectName: string; context: string }): AiContextRow {
  return withLock(() => {
    const { rows } = readAiContexts();
    const wanted = body.projectName.trim().toLowerCase();
    let row = rows.find((r) => r.projectName.trim().toLowerCase() === wanted);
    if (row) {
      row.context = body.context;
      row.updatedAt = now();
    } else {
      row = { _id: newId(), projectName: body.projectName.trim(), context: body.context, updatedAt: now() };
      rows.push(row);
    }
    writeRows(aiContextFile(), rows);
    return row;
  });
}

export function updateAiContext(id: string, body: { projectName: string; context: string }): AiContextRow {
  return withLock(() => {
    const { rows } = readAiContexts();
    const row = rows.find((r) => r._id === id);
    if (!row) {
      throw new Error("Local AI Context not found.");
    }
    row.projectName = body.projectName.trim();
    row.context = body.context;
    row.updatedAt = now();
    writeRows(aiContextFile(), rows);
    return row;
  });
}

export function deleteAiContext(id: string): boolean {
  return withLock(() => {
    const { rows } = readAiContexts();
    const next = rows.filter((r) => r._id !== id);
    writeRows(aiContextFile(), next);
    return next.length !== rows.length;
  });
}

// ---------------------------------------------------------------- credentials

const readCredentials = () => readJson<RowsFile<CredentialSetDetail>>(credentialsFile(), { rows: [] });

const summary = (row: CredentialSetDetail): CredentialSetRow => {
  const { cipher: _cipher, ...rest } = row;
  return rest;
};

export function listCredentialSets(): CredentialSetRow[] {
  return readCredentials().rows.map(summary);
}

export function listCredentialSetDetails(): CredentialSetDetail[] {
  return readCredentials().rows;
}

export function getCredentialSet(id: string): CredentialSetDetail {
  const row = readCredentials().rows.find((r) => r._id === id);
  if (!row) {
    throw new Error("Local credential set not found.");
  }
  return row;
}

type CredentialBody = Pick<CredentialSetDetail, "name" | "description" | "projectTags" | "keyCount" | "cipher">;

export function createCredentialSet(body: CredentialBody): CredentialSetRow {
  return withLock(() => {
    const { rows } = readCredentials();
    const ts = now();
    const row: CredentialSetDetail = { ...body, _id: newId(), locked: false, createdAt: ts, updatedAt: ts };
    rows.push(row);
    writeRows(credentialsFile(), rows);
    return summary(row);
  });
}

export function updateCredentialSet(id: string, body: CredentialBody): CredentialSetRow {
  return withLock(() => {
    const { rows } = readCredentials();
    const row = rows.find((r) => r._id === id);
    if (!row) {
      throw new Error("Local credential set not found.");
    }
    Object.assign(row, body, { updatedAt: now() });
    writeRows(credentialsFile(), rows);
    return summary(row);
  });
}

export function setCredentialSetLocked(id: string, locked: boolean): CredentialSetRow {
  return withLock(() => {
    const { rows } = readCredentials();
    const row = rows.find((r) => r._id === id);
    if (!row) {
      throw new Error("Local credential set not found.");
    }
    row.locked = locked;
    row.updatedAt = now();
    writeRows(credentialsFile(), rows);
    return summary(row);
  });
}

export function deleteCredentialSet(id: string): boolean {
  return withLock(() => {
    const { rows } = readCredentials();
    const next = rows.filter((r) => r._id !== id);
    writeRows(credentialsFile(), next);
    return next.length !== rows.length;
  });
}

// ---------------------------------------------------------------- summary

export interface LocalCounts {
  graphs: number;
  prompts: number;
  aiContexts: number;
  credentials: number;
}

export function counts(): LocalCounts {
  return {
    graphs: listGraphNames().length,
    prompts: listPromptProjects().reduce((n, p) => n + listPrompts(p).length, 0),
    aiContexts: listAiContexts().length,
    credentials: listCredentialSets().length,
  };
}

export function isEmpty(): boolean {
  const c = counts();
  return c.graphs + c.prompts + c.aiContexts + c.credentials === 0;
}
